@pytest.fixture(scope="module")
def built_artifacts(tmp_path_factory: pytest.TempPathFactory) -> tuple[Path, Path]:
    output_dir = tmp_path_factory.mktemp("artifacts")
    subprocess.run(
        ["uv", "build", "--wheel", "--sdist", "--out-dir", str(output_dir)],
        cwd=PROJECT_ROOT,
        check=True,
        capture_output=True,
        text=True,
    )
    wheel = next(output_dir.glob("*.whl"))
    sdist = next(output_dir.glob("*.tar.gz"))
    return wheel, sdist


def test_wheel_pins_runtime_dependencies(built_artifacts: tuple[Path, Path]) -> None:
    wheel, _ = built_artifacts
    with ZipFile(wheel) as archive:
        metadata_path = next(
            name for name in archive.namelist() if name.endswith(".dist-info/METADATA")
        )
        metadata = BytesParser().parsebytes(archive.read(metadata_path))

    assert metadata.get_all("Requires-Dist") == [
        "fastapi==0.153.0",
        "httpx==0.28.1",
        "lxml==6.0.2",
        "numpy==2.3.4",
        "onnxruntime==1.23.2",
        "qdrant-client==1.19.1",
        "ragbits-core==1.7.0.dev202605130309",
        "tokenizers==0.23.3",
        "uvicorn==0.54.0",
    ]


def test_wheel_contains_only_runtime_package_files(
    built_artifacts: tuple[Path, Path],
) -> None:
    wheel, _ = built_artifacts
    with ZipFile(wheel) as archive:
        assert set(archive.namelist()) == EXPECTED_WHEEL_FILES


def test_sdist_contains_only_release_sources(
    built_artifacts: tuple[Path, Path],
) -> None:
    _, sdist = built_artifacts
    with tarfile.open(sdist, mode="r:gz") as archive:
        files = {
            PurePosixPath(*PurePosixPath(member.name).parts[1:]).as_posix()
            for member in archive.getmembers()
            if member.isfile()
        }

    assert files == EXPECTED_SDIST_FILES
    assert not any(
        blocked in PurePosixPath(path).parts
        for path in files
        for blocked in ("baseline", "docs", "reproduction")
    )
    assert not any(path.endswith(".bundle") for path in files)
    assert not any(
        path.startswith(("data/archives/", "data/manifests/", "data/LICENSES/"))
        for path in files
    )


def test_build_backend_is_exactly_pinned() -> None:
    with (PROJECT_ROOT / "pyproject.toml").open("rb") as file:
        pyproject = tomllib.load(file)

    assert pyproject["build-system"]["requires"] == ["hatchling==1.32.4"]
